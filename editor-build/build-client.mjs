import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { Script } from 'node:vm';
import { build } from 'esbuild';
import { buildEngine, pinnedBuildOptions } from './build.mjs';

const target = new URL('../client.bundle.js', import.meta.url);
const authorSource = await readFile(new URL('../client.js', import.meta.url), 'utf8');
const sha = createHash('sha256').update(authorSource).digest('hex');
const engine = await buildEngine();
const { outputFiles: [pageFind] } = await build({ ...pinnedBuildOptions, entryPoints: ['editor-build/page-find-entry.js'],
  format: 'iife', globalName: '__dshInspirationPageFind', platform: 'browser', target: 'es2022', minify: true, charset: 'utf8' });
const code = `/* Generated by editor-build/build-client.mjs; client.js sha256 ${sha}. */\n(() => {\n` +
  `let editorAPI;\nconst __dshInspirationContinuousMarkdown = { createContinuousMarkdown(...args) {\n` +
  `  editorAPI ??= (() => {\n${engine}\nreturn __dshInspirationContinuousMarkdown;\n  })();\n` +
  `  return editorAPI.createContinuousMarkdown(...args);\n}};\n${pageFind.text}\n${authorSource}\n})();\n`;
new Script(code, { filename: 'client.bundle.js' });
if (process.argv[2] === '--check') {
  if (code !== await readFile(target, 'utf8')) throw new Error('client.bundle.js is out of date; run npm run build:client');
} else if (process.argv.length === 2) {
  await writeFile(target, code, 'utf8');
} else {
  throw new Error('Usage: node editor-build/build-client.mjs [--check]');
}
